# ---------------------------------------------------------------------------
# 6.2 广场业务层错误码（自定义，70000 段）
# ---------------------------------------------------------------------------
class BizError(Exception):
    """广场业务错误。携带业务码、HTTP 状态、面向用户文案与面向服务方英文原因。"""

    def __init__(self, code: str, http_status: int, message: str, reason: str = ""):
        self.code = code
        self.http_status = http_status
        self.message = message          # 面向用户，中文可读
        self.reason = reason            # 面向服务方，英文原因（可空）
        super().__init__(code)


BIZ_ERRORS = {
    "70001": (400, "投稿必填字段缺失或校验失败", "invalid request body"),
    "70002": (403, "非作者，无权操作他人作品", "horizontal privilege escalation"),
    "70003": (403, "角色无权执行该审核动作", "insufficient review role"),
    "70004": (409, "同一项目已存在有效投稿", "duplicate submission for project"),
    "70005": (404, "作品不存在或已下架", "work not found"),
    "70006": (423, "作品审核中，暂不可编辑", "work under review"),
    "70007": (403, "受限作品，无权访问", "restricted work"),
}


def biz(code: str, request_id: str = "") -> dict:
    """构造一个广场业务错误响应体（标准 10.3 格式）。"""
    http, msg, reason = BIZ_ERRORS[code]
    body = {"code": code, "message": msg, "data": None, "requestId": request_id}
    if reason:
        body["data"] = {"reason": reason}
    return body


def biz_http(code: str) -> int:
    """返回业务码对应的 HTTP 状态码。"""
    return BIZ_ERRORS[code][0]
